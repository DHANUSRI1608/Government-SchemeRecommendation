export const supportedLanguages = [
  { code: "en", label: "English" },
  { code: "hi", label: "हिन्दी" },
  { code: "ta", label: "தமிழ்" },
  { code: "te", label: "తెలుగు" },
  { code: "kn", label: "ಕನ್ನಡ" },
  { code: "ml", label: "മലയാളം" }
];

const LanguageContext = createContext(null);

function getInitialLanguage() {
  const savedLanguage = window.localStorage.getItem("farmscheme-language");
  if (supportedLanguages.some(({ code }) => code === savedLanguage)) return savedLanguage;

  const browserLanguage = window.navigator.language?.split("-")[0];
  return supportedLanguages.some(({ code }) => code === browserLanguage) ? browserLanguage : "en";
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(getInitialLanguage);

  useEffect(() => {
    window.localStorage.setItem("farmscheme-language", language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (text) => translations[language]?.[text] ?? text
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useTranslation() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useTranslation must be used within a LanguageProvider");
  return context;
}
